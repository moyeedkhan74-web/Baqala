require('dotenv').config({ path: 'd:/baqala project/server/.env' });
const mongoose = require('mongoose');
const Notification = require('./models/Notification');
const User = require('./models/User');

async function verifyNotifications() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected!');

    // 1. Find a test user (or create one)
    const testUser = await User.findOne({ email: process.env.SMTP_USER }) || await User.findOne();
    if (!testUser) {
      console.error('No users found in database to test with.');
      return;
    }

    console.log(`Testing with user: ${testUser.name} (${testUser._id})`);

    // 2. Create a test notification
    const notification = await Notification.create({
      recipient: testUser._id,
      title: '🧪 Test Notification',
      message: 'This is a test notification generated by the verification script.',
      type: 'info'
    });

    console.log('Success! Test notification created:', notification._id);

    // 3. List recent notifications for this user
    const recent = await Notification.find({ recipient: testUser._id }).sort({ createdAt: -1 }).limit(5);
    console.log('\nRecent notifications for user:');
    recent.forEach(n => {
      console.log(`- [${n.createdAt.toISOString()}] ${n.title}: ${n.message}`);
    });

  } catch (error) {
    console.error('Verification failed:', error);
  } finally {
    await mongoose.connection.close();
    console.log('Connection closed.');
  }
}

verifyNotifications();
